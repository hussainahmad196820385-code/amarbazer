export function getTranslation(lang: Language, key: keyof typeof translations['en']): string {
  const translationsMap = translations as any;
  const baseTranslation = (translationsMap[lang] && translationsMap[lang][key]) || translations['en'][key] || key;

  // Intercept and apply custom English to Bangla replacements if language is 'bn'
  if (lang === 'bn') {
    try {
      const customReplacementsStr = localStorage.getItem('customReplacements');
      if (customReplacementsStr) {
        const replacements = JSON.parse(customReplacementsStr);
        if (Array.isArray(replacements)) {
          let activeRole = 'customer';
          const userStr = localStorage.getItem('currentUser');
          if (userStr) {
            try {
              const userObj = JSON.parse(userStr);
              if (userObj && userObj.role) {
                activeRole = userObj.role;
              }
            } catch (_) {}
          }

          const englishText = translations['en'][key] || '';
          const match = replacements.find((r: any) => {
            const roleMatches = r.userRole === 'all' || r.userRole === activeRole;
            const textMatches = 
              r.originalText.toLowerCase() === String(key).toLowerCase() ||
              r.originalText.toLowerCase() === englishText.toLowerCase() ||
              r.originalText === baseTranslation;
            return roleMatches && textMatches;
          });

          if (match && match.replacementText) {
            return match.replacementText;
          }
        }
      }
    } catch (e) {
      console.warn('Error applying custom replacements:', e);
    }
  }

  return baseTranslation;
}
